-- 1. Tambah kolom is_ai_generated ke modul_remedial (jika tabel sudah ada)
do $$
begin
  if exists (select 1 from information_schema.tables where table_name = 'modul_remedial') then
    alter table public.modul_remedial 
      add column if not exists is_ai_generated boolean not null default false,
      add column if not exists id_mahasiswa bigint references public.mahasiswa (id_mahasiswa) on delete cascade,
      add column if not exists id_attempt_ke bigint,
      add column if not exists generated_at timestamptz not null default now(),
      add column if not exists source_material text; -- JSON string of source: wrong questions, student answers, module material
  end if;
end
$$;

-- 2. Index untuk query AI material per mahasiswa
create index if not exists idx_modul_remedial_ai_mahasiswa 
  on public.modul_remedial (id_mahasiswa, id_modul, is_ai_generated)
  where is_ai_generated = true;

-- 3. Tabel untuk melacak job generasi AI (audit & debugging)
create table if not exists public.ai_remedial_generation_job (
  id_job           bigint generated by default as identity primary key,
  id_mahasiswa     bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  id_modul         bigint not null references public.modul (id_modul) on delete cascade,
  id_attempt_ke    bigint not null,
  status           text not null default 'pending' check (status in ('pending', 'processing', 'completed', 'failed')),
  weak_areas       jsonb, -- sub-topik yang lemah
  generated_count  int not null default 0,
  error_message    text,
  created_at       timestamptz not null default now(),
  completed_at     timestamptz
);

create index if not exists idx_ai_remedial_job_mahasiswa 
  on public.ai_remedial_generation_job (id_mahasiswa, id_modul, id_attempt_ke);

alter table public.ai_remedial_generation_job enable row level security;

drop policy if exists "Allow all on ai_remedial_generation_job" on public.ai_remedial_generation_job;
create policy "Allow all on ai_remedial_generation_job"
  on public.ai_remedial_generation_job
  for all
  using (true)
  with check (true);

-- 4. RLS policies untuk modul_remedial (update existing)
alter table public.modul_remedial enable row level security;

drop policy if exists "Allow all on modul_remedial" on public.modul_remedial;
create policy "Allow all on modul_remedial"
  on public.modul_remedial
  for all
  using (true)
  with check (true);

