-- 1. Knowledge Tracing: tingkat pemahaman mahasiswa per sub-topik
create table if not exists public.konsep_mahasiswa (
  id_konsep        bigint generated by default as identity primary key,
  id_mahasiswa     bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  id_sub_topik     bigint not null references public.sub_topik (id_sub_topik) on delete cascade,
  id_modul         bigint not null references public.modul (id_modul) on delete cascade,
  tingkat_pemahaman numeric(4,3) not null default 0.5 check (tingkat_pemahaman >= 0 and tingkat_pemahaman <= 1),
  total_jawaban    bigint not null default 0,
  total_benar      bigint not null default 0,
  updated_at       timestamptz not null default now(),
  unique (id_mahasiswa, id_sub_topik, id_modul)
);

create index if not exists idx_konsep_mahasiswa_mahasiswa on public.konsep_mahasiswa (id_mahasiswa);
create index if not exists idx_konsep_mahasiswa_sub_topik on public.konsep_mahasiswa (id_sub_topik);

alter table public.konsep_mahasiswa enable row level security;

drop policy if exists "Allow all on konsep_mahasiswa" on public.konsep_mahasiswa;
create policy "Allow all on konsep_mahasiswa"
  on public.konsep_mahasiswa
  for all
  using (true)
  with check (true);


-- 2. ML Remedial Recommendation history (audit trail)
create table if not exists public.ml_remedial_recommendation (
  id_ml_remedial   bigint generated by default as identity primary key,
  id_mahasiswa     bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  id_modul         bigint not null references public.modul (id_modul) on delete cascade,
  id_remedial      bigint references public.modul_remedial (id_remedial) on delete cascade,
  id_attempt_ke    bigint not null,
  skor_relevansi   numeric(4,3) not null check (skor_relevansi >= 0 and skor_relevansi <= 1),
  alasan           text,
  tipe_rekomendasi text not null default 'content_similarity',
  created_at       timestamptz not null default now()
);

create index if not exists idx_ml_remedial_mahasiswa on public.ml_remedial_recommendation (id_mahasiswa, id_modul, id_attempt_ke);

alter table public.ml_remedial_recommendation enable row level security;

drop policy if exists "Allow all on ml_remedial_recommendation" on public.ml_remedial_recommendation;
create policy "Allow all on ml_remedial_recommendation"
  on public.ml_remedial_recommendation
  for all
  using (true)
  with check (true);


-- 3. Kolom embedding untuk content-based filtering (vector 1536 untuk OpenAI text-embedding-3-small)
-- Catatan: Supabase pgvector extension diperlukan. Jika tidak tersedia, embedding bisa diisi NULL
-- dan sistem akan fallback ke keyword matching.
do $$
begin
  if not exists (select 1 from pg_extension where extname = 'vector') then
    create extension if not exists vector;
  end if;
end
$$;

alter table public.soal add column if not exists embedding vector(1536);
alter table public.modul_remedial add column if not exists embedding vector(1536);

