  on public.riwayat_perolehan_xp
  for all
  using (true)
  with check (true);

-- 2. RPC simpan_riwayat_jawaban
create or replace function public.simpan_riwayat_jawaban(
  p_id_mahasiswa bigint,
  p_id_modul bigint,
  p_rows jsonb
)
returns void
language plpgsql
security definer
as $$
begin
  -- Hapus riwayat snapshot sebelumnya untuk modul dan mahasiswa ini
  delete from public.riwayat_jawaban_kuis
  where id_mahasiswa = p_id_mahasiswa
    and id_modul = p_id_modul;

  -- Insert baris-baris baru dari JSON
  insert into public.riwayat_jawaban_kuis (id_mahasiswa, id_modul, id_soal, id_jawaban, is_benar, created_at)
  select
    p_id_mahasiswa,
    p_id_modul,
    (item->>'id_soal')::bigint,
    nullif(item->>'id_jawaban', '')::bigint,
    coalesce((item->>'is_benar')::boolean, false),
    now()
  from jsonb_array_elements(p_rows) as item;
end;
$$;

-- 3. RPC submit_attempt_modul
create or replace function public.submit_attempt_modul(
  p_id_mahasiswa bigint,
  p_id_modul bigint,
  p_nilai numeric
)
returns table (
  o_attempt_ke bigint,
  o_lulus boolean,
  o_nilai_terbaik numeric,
  o_xp integer,
  o_elo integer,
  o_elo_delta integer
)
language plpgsql
security definer
as $$
declare
  v_pass_score numeric := 80;
  v_id_level bigint := 1;
  v_base_xp integer := 30;
  v_attempt_ke bigint;
  v_sudah_pernah_lulus boolean := false;
  v_lulus_sekarang boolean := false;
  v_xp_didapat integer := 0;
  v_nilai_terbaik numeric := p_nilai;
  v_curr_xp integer := 0;
  v_curr_elo integer := 1000;
  v_elo_difficulty numeric := 1000;
  v_elo_k numeric := 32;
  v_elo_expected numeric;
  v_elo_delta integer := 0;
  v_elo_sesudah integer := 1000;
begin
  -- 1. Ambil data modul
  select coalesce(parameter_nilai, 80), coalesce(id_level, 1)
  into v_pass_score, v_id_level
  from public.modul
  where id_modul = p_id_modul;

  -- Tentukan base XP berdasarkan level modul
  if v_id_level = 1 then
    v_base_xp := 20;
    v_elo_difficulty := 950;
  elsif v_id_level = 2 then
    v_base_xp := 50;
    v_elo_difficulty := 1100;
  elsif v_id_level = 3 then
    v_base_xp := 100;
    v_elo_difficulty := 1250;
  else
    v_base_xp := 30;
    v_elo_difficulty := 1000;
  end if;

  -- 2. Ambil profil mahasiswa
  select coalesce(total_xp, 0), coalesce(elo, 1000)
  into v_curr_xp, v_curr_elo
  from public.mahasiswa
  where id_mahasiswa = p_id_mahasiswa;

  -- 3. Cek apakah pernah lulus modul ini sebelumnya
  select exists (
    select 1 from public.attempt_kuis_modul
    where id_mahasiswa = p_id_mahasiswa
      and id_modul = p_id_modul
      and nilai >= v_pass_score
  ) into v_sudah_pernah_lulus;

  -- 4. Hitung attempt_ke berikutnya
  select coalesce(max(attempt_ke), 0) + 1
  into v_attempt_ke
  from public.attempt_kuis_modul
  where id_mahasiswa = p_id_mahasiswa
    and id_modul = p_id_modul;

  v_lulus_sekarang := (p_nilai >= v_pass_score);

  -- 5. Hitung XP yang didapat (idempotent, 100% jika pertama lulus, 50% jika retake lulus)
  if v_lulus_sekarang then
    if not v_sudah_pernah_lulus then
      v_xp_didapat := v_base_xp;
    else
      v_xp_didapat := floor(v_base_xp * 0.5)::integer;
    end if;
  else
    v_xp_didapat := 0;
  end if;

  -- 6. Hitung Elo delta
  v_elo_expected := 1.0 / (1.0 + power(10.0, (v_elo_difficulty - v_curr_elo) / 400.0));
  if v_lulus_sekarang then
    v_elo_delta := greatest(1, round(v_elo_k * (1.0 - v_elo_expected)))::integer;
  else
    v_elo_delta := -greatest(1, round(v_elo_k * v_elo_expected))::integer;
  end if;
  v_elo_sesudah := greatest(100, v_curr_elo + v_elo_delta);

  -- 7. Simpan ke attempt_kuis_modul
  insert into public.attempt_kuis_modul (id_mahasiswa, id_modul, attempt_ke, nilai)
  values (p_id_mahasiswa, p_id_modul, v_attempt_ke, p_nilai);

  -- 8. Hitung nilai tertinggi
  select coalesce(max(nilai), p_nilai)
  into v_nilai_terbaik
  from public.attempt_kuis_modul
  where id_mahasiswa = p_id_mahasiswa
    and id_modul = p_id_modul;

  -- 9. Catat riwayat XP (idempotensi) dan update total_xp mahasiswa
  if v_xp_didapat > 0 then
    insert into public.riwayat_perolehan_xp (id_mahasiswa, sumber_aktivitas, id_referensi, attempt_ke, xp_diperoleh)
    values (p_id_mahasiswa, 'kuis_modul', p_id_modul, v_attempt_ke, v_xp_didapat)
    on conflict (id_mahasiswa, sumber_aktivitas, id_referensi, attempt_ke) do nothing;

    -- Update total_xp mahasiswa
    update public.mahasiswa
    set total_xp = coalesce(total_xp, 0) + v_xp_didapat,
        elo = v_elo_sesudah
    where id_mahasiswa = p_id_mahasiswa;
  else
    -- Hanya update elo jika tidak ada xp didapat
    update public.mahasiswa
    set elo = v_elo_sesudah
    where id_mahasiswa = p_id_mahasiswa;
  end if;

  -- 10. Update progress_modul
  insert into public.progress_modul (id_mahasiswa, id_modul, nilai, selesai, kuis_dicoba, materi_dilihat)
  values (p_id_mahasiswa, p_id_modul, v_nilai_terbaik, (v_nilai_terbaik >= v_pass_score), true, true)
  on conflict (id_mahasiswa, id_modul)
  do update set
    nilai = greatest(public.progress_modul.nilai, v_nilai_terbaik),
    selesai = (greatest(public.progress_modul.nilai, v_nilai_terbaik) >= v_pass_score),
    kuis_dicoba = true;

  -- 11. Kembalikan hasil
  return query select
    v_attempt_ke,
    v_lulus_sekarang,
    v_nilai_terbaik,
    v_xp_didapat,
    v_elo_sesudah,
    v_elo_delta;
end;
$$;
