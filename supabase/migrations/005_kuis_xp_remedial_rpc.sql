-- 1. Tabel untuk pencatatan perolehan XP (mencegah XP ganda secara database constraint)
create table if not exists public.riwayat_perolehan_xp (
  id_perolehan_xp bigint generated by default as identity primary key,
  id_mahasiswa bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  sumber_aktivitas text not null, -- 'kuis_modul', 'kuis_vn', 'ujian_mandiri'
  id_referensi bigint not null,   -- id_modul atau id_quis
  attempt_ke int not null default 1,
  xp_diperoleh int not null default 0,
  created_at timestamptz not null default now(),
  constraint uq_riwayat_xp_mahasiswa_aktivitas_attempt unique (id_mahasiswa, sumber_aktivitas, id_referensi, attempt_ke)
);

create index if not exists idx_riwayat_perolehan_xp_mhs 
  on public.riwayat_perolehan_xp (id_mahasiswa, sumber_aktivitas, id_referensi);

alter table public.riwayat_perolehan_xp enable row level security;

drop policy if exists "Allow all on riwayat_perolehan_xp" on public.riwayat_perolehan_xp;
