-- Persist idempotent answer events and Bayesian Knowledge Tracing mastery.

alter table public.soal
  add column if not exists difficulty_rating integer
  check (difficulty_rating between 950 and 1250);

comment on column public.soal.difficulty_rating is
  'Elo difficulty rating used to personalize quiz question selection (950 easy, 1100 medium, 1250 hard).';

create table if not exists public.adaptive_learning_response (
  id_response bigint generated by default as identity primary key,
  id_mahasiswa bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  id_modul bigint not null references public.modul (id_modul) on delete cascade,
  id_sub_topik bigint references public.sub_topik (id_sub_topik) on delete set null,
  id_soal bigint not null references public.soal (id_soal) on delete cascade,
  submission_key uuid not null,
  is_benar boolean not null,
  created_at timestamptz not null default now(),
  constraint uq_adaptive_learning_response_submission
    unique (id_mahasiswa, id_modul, submission_key, id_soal)
);

create index if not exists idx_adaptive_learning_response_student_module
  on public.adaptive_learning_response (id_mahasiswa, id_modul, created_at desc);

alter table public.adaptive_learning_response enable row level security;

revoke all on public.adaptive_learning_response from anon, authenticated;
grant all on public.adaptive_learning_response to service_role;
grant usage, select on sequence public.adaptive_learning_response_id_response_seq
  to service_role;

create or replace function public.is_current_student(p_id_mahasiswa bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public."user" u
    where u.auth_user_id = auth.uid()
      and u.id_mahasiswa = p_id_mahasiswa
  );
$$;

revoke all on function public.is_current_student(bigint) from public, anon;
grant execute on function public.is_current_student(bigint) to authenticated;

alter table public.konsep_mahasiswa enable row level security;
drop policy if exists "Allow all on konsep_mahasiswa" on public.konsep_mahasiswa;
drop policy if exists "Students read own BKT mastery" on public.konsep_mahasiswa;
create policy "Students read own BKT mastery"
  on public.konsep_mahasiswa for select to authenticated
  using (public.is_current_student(id_mahasiswa));
revoke all on public.konsep_mahasiswa from anon, authenticated;
grant select on public.konsep_mahasiswa to authenticated;
grant all on public.konsep_mahasiswa to service_role;

create or replace function public.record_bkt_responses(
  p_id_mahasiswa bigint,
  p_id_modul bigint,
  p_submission_key uuid,
  p_rows jsonb
)
returns table (o_processed integer, o_unmapped integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item jsonb;
  v_id_soal bigint;
  v_id_jawaban bigint;
  v_id_sub_topik bigint;
  v_lo_code text;
  v_is_benar boolean;
  v_prior numeric;
  v_posterior numeric;
  v_mastery numeric;
  v_guess numeric := 0.20;
  v_slip numeric := 0.10;
  v_learning numeric := 0.20;
  v_processed integer := 0;
  v_unmapped integer := 0;
  v_inserted bigint;
begin
  if p_id_mahasiswa is null or p_id_modul is null or p_submission_key is null
    or p_rows is null or jsonb_typeof(p_rows) <> 'array'
    or jsonb_array_length(p_rows) < 1 or jsonb_array_length(p_rows) > 50 then
    raise exception 'Invalid BKT submission';
  end if;

  for v_item in select value from jsonb_array_elements(p_rows)
  loop
    v_id_soal := nullif(v_item->>'id_soal', '')::bigint;
    v_id_jawaban := nullif(v_item->>'id_jawaban', '')::bigint;

    select s.id_sub_topik, s.lo_code,
           case
             when v_id_jawaban is null then false
             else coalesce(j.jawaban_benar, false)
           end
      into v_id_sub_topik, v_lo_code, v_is_benar
      from public.soal s
      left join public.jawaban j
        on j.id_jawaban = v_id_jawaban
       and j.id_soal = s.id_soal
      where s.id_soal = v_id_soal
        and s.id_modul = p_id_modul;

    if not found then
      raise exception 'Question does not belong to this module';
    end if;

    if v_id_jawaban is not null and not exists (
      select 1
      from public.jawaban j
      where j.id_jawaban = v_id_jawaban
        and j.id_soal = v_id_soal
    ) then
      raise exception 'Selected answer does not belong to the question';
    end if;

    if v_id_sub_topik is null and v_lo_code is not null then
      select st.id_sub_topik
        into v_id_sub_topik
        from public.sub_topik st
        where st.id_modul = p_id_modul
          and st.lo_code = v_lo_code
        limit 1;
    end if;

    insert into public.adaptive_learning_response (
      id_mahasiswa, id_modul, id_sub_topik, id_soal, submission_key, is_benar
    )
    values (
      p_id_mahasiswa, p_id_modul, v_id_sub_topik, v_id_soal, p_submission_key, v_is_benar
    )
    on conflict (id_mahasiswa, id_modul, submission_key, id_soal) do nothing
    returning id_response into v_inserted;

    if v_inserted is null then
      continue;
    end if;

    if v_id_sub_topik is null then
      v_unmapped := v_unmapped + 1;
      continue;
    end if;

    insert into public.konsep_mahasiswa (
      id_mahasiswa, id_sub_topik, id_modul, tingkat_pemahaman, total_jawaban, total_benar
    )
    values (p_id_mahasiswa, v_id_sub_topik, p_id_modul, 0.10, 0, 0)
    on conflict (id_mahasiswa, id_sub_topik, id_modul) do nothing;

    select km.tingkat_pemahaman
      into v_prior
      from public.konsep_mahasiswa km
      where km.id_mahasiswa = p_id_mahasiswa
        and km.id_sub_topik = v_id_sub_topik
        and km.id_modul = p_id_modul
      for update;

    if v_is_benar then
      v_posterior := (v_prior * (1 - v_slip))
        / ((v_prior * (1 - v_slip)) + ((1 - v_prior) * v_guess));
    else
      v_posterior := (v_prior * v_slip)
        / ((v_prior * v_slip) + ((1 - v_prior) * (1 - v_guess)));
    end if;

    v_mastery := v_posterior + ((1 - v_posterior) * v_learning);

    update public.konsep_mahasiswa
      set tingkat_pemahaman = greatest(0, least(1, v_mastery)),
          total_jawaban = total_jawaban + 1,
          total_benar = total_benar + case when v_is_benar then 1 else 0 end,
          updated_at = now()
      where id_mahasiswa = p_id_mahasiswa
        and id_sub_topik = v_id_sub_topik
        and id_modul = p_id_modul;

    v_processed := v_processed + 1;
  end loop;

  return query select v_processed, v_unmapped;
end;
$$;

revoke all on function public.record_bkt_responses(bigint, bigint, uuid, jsonb)
  from public, anon, authenticated;
grant execute on function public.record_bkt_responses(bigint, bigint, uuid, jsonb)
  to service_role;
