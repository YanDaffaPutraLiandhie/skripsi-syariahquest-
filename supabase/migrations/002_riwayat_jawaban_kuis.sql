-- Menyimpan snapshot jawaban terakhir mahasiswa untuk setiap modul.
create table if not exists public.riwayat_jawaban_kuis (
  id_riwayat_jawaban bigint generated by default as identity primary key,
  id_mahasiswa bigint not null references public.mahasiswa (id_mahasiswa) on delete cascade,
  id_modul bigint not null references public.modul (id_modul) on delete cascade,
  id_soal bigint not null references public.soal (id_soal) on delete cascade,
  id_jawaban bigint references public.jawaban (id_jawaban) on delete set null,
  is_benar boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_riwayat_jawaban_kuis_mahasiswa_modul
  on public.riwayat_jawaban_kuis (id_mahasiswa, id_modul);

alter table public.riwayat_jawaban_kuis enable row level security;

drop policy if exists "Allow all on riwayat_jawaban_kuis"
  on public.riwayat_jawaban_kuis;
create policy "Allow all on riwayat_jawaban_kuis"
  on public.riwayat_jawaban_kuis
  for all
  using (true)
  with check (true);